#!/usr/bin/env python3
"""Draws the sample art of the template into assets/*.png (indexed PNGs). Run it once if you want the originals back; your own
game replaces these files with art from any pixel editor (indexed colour, 8x8 tiles) and never needs this script.

  tools/make_art.py [assets-dir]
"""
import os
import sys

from PIL import Image

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets")

PAL = {                       # palette index -> colour (index 0 is the see-through one in the PNGs that have any)
    0: (255, 0, 255),
    1: (80, 150, 255), 2: (130, 190, 255), 3: (255, 255, 255), 4: (200, 215, 240), 5: (70, 170, 60), 6: (40, 120, 40),
    7: (150, 100, 50), 8: (100, 65, 30), 9: (230, 60, 60), 10: (140, 20, 30), 11: (255, 255, 255), 12: (10, 10, 10),
    13: (20, 20, 60), 14: (230, 230, 255), 15: (255, 240, 120), 17: (255, 210, 40), 18: (230, 120, 20), 20: (30, 140, 50),
    21: (20, 100, 35), 22: (110, 70, 30),
}
SKY, SKY2, CLOUD, CLOUD2, GRASS, GRASS2, DIRT, DIRT2 = 1, 2, 3, 4, 5, 6, 7, 8
HERO, HERO2, WHITE, BLACK, BOX, BORDER, TEXT, BIRD, BIRD2, BUSH, BUSH2, TRUNK = 9, 10, 11, 12, 13, 14, 15, 17, 18, 20, 21, 22


def save(name, w, h, pixels, transparent):
    im = Image.new("P", (w, h))
    flat = []
    for i in range(256):
        flat.extend(PAL.get(i, (0, 0, 0)))
    im.putpalette(flat)
    im.putdata(pixels)
    kw = {"transparency": 0} if transparent else {}
    im.save(os.path.join(OUT, name), optimize=True, **kw)


def tile(fn):
    return [fn(x, y) for y in range(8) for x in range(8)]


def blit(canvas, w, tx, ty, t):
    for y in range(8):
        for x in range(8):
            canvas[(ty * 8 + y) * w + tx * 8 + x] = t[y * 8 + x]


# ---- ground.png: BG0, 512 x 512, opaque -----------------------------------------------------------------------------------------------
def grass(x, y):
    if y < 3:
        return GRASS2 if (x * 5 + y * 3) % 7 == 0 else GRASS
    return DIRT2 if (x * 3 + y * 5) % 11 == 0 else DIRT


def dirt(x, y):
    return DIRT2 if (x * 7 + y * 3) % 9 == 0 else DIRT


def ground():
    w = 512
    c = [0] * (w * 512)
    for ty in range(64):
        t = (tile(lambda x, y: SKY) if ty < 8 else tile(lambda x, y: SKY2) if ty < 20 else tile(grass) if ty == 20 else
             tile(dirt) if ty < 24 else tile(lambda x, y: DIRT2))
        for tx in range(64):
            blit(c, w, tx, ty, t)
    save("ground.png", w, 512, c, False)


# ---- clouds.png: BG1, 512 x 512, index 0 see-through ----------------------------------------------------------------------------------
def cloud_l(x, y):
    if y < 2 or y > 6:
        return 0
    edge = 3 - (y if y < 4 else 7 - y)
    return 0 if x < edge else (CLOUD2 if y > 4 else CLOUD)


def cloud_m(x, y):
    if y < 1 or y > 6:
        return 0
    return CLOUD2 if y > 4 else CLOUD


def bush_top(x, y):
    d = abs(x - 3.5)
    if y < 2 + d * 0.9:
        return 0
    return BUSH2 if (x + y) % 4 == 0 else BUSH


def clouds():
    w = 512
    c = [0] * (w * 512)
    T = {"cl": tile(cloud_l), "cm": tile(cloud_m), "cr": tile(lambda x, y: cloud_l(7 - x, y)), "bt": tile(bush_top),
         "b": tile(lambda x, y: BUSH2 if (x * 3 + y) % 5 == 0 else BUSH), "tr": tile(lambda x, y: TRUNK if 2 <= x <= 5 else 0)}
    for cx, cy, n in ((3, 3, 3), (14, 5, 4), (27, 3, 3), (38, 6, 4), (50, 4, 3), (58, 7, 3)):
        blit(c, w, cx, cy, T["cl"])
        for k in range(1, n - 1):
            blit(c, w, cx + k, cy, T["cm"])
        blit(c, w, cx + n - 1, cy, T["cr"])
    for bx in (6, 20, 33, 47, 60):
        blit(c, w, bx, 18, T["bt"])
        blit(c, w, bx, 19, T["b"])
    for tx in (11, 41):
        for ty in (15, 16, 17, 18, 19):
            blit(c, w, tx, ty, T["tr"])
        blit(c, w, tx, 14, T["bt"])
    save("clouds.png", w, 512, c, True)


# ---- hero.png (16 x 16) and bird.png (16 x 8): sprites, index 0 see-through ---------------------------------------------------------
def hero():
    h = [[0] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            if (1 <= x <= 14 and 1 <= y <= 14) and not (x in (1, 14) and y in (1, 14)):
                h[y][x] = HERO2 if (x in (1, 14) or y in (1, 14)) else HERO
    for ex in (4, 9):
        for dy in range(2):
            for dx in range(3):
                h[5 + dy][ex + dx] = WHITE
        h[6][ex + 1] = h[6][ex + 2] = BLACK
    for x in range(5, 11):
        h[11][x] = HERO2
    h[10][4] = h[10][11] = HERO2
    save("hero.png", 16, 16, [v for row in h for v in row], True)


def bird():
    b = [[0] * 16 for _ in range(8)]
    for y in range(8):
        for x in range(16):
            dx, dy = (x - 7.5) / 7.0, (y - 4.5) / 3.2
            if dx * dx + dy * dy <= 1.0:
                b[y][x] = BIRD2 if (y >= 5 and 3 <= x <= 10) else BIRD
    b[3][11] = BLACK
    b[4][14] = b[4][15] = BIRD2
    save("bird.png", 16, 8, [v for row in b for v in row], True)


